import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { filterRecords, makeInvestigation, readInvestigation, INITIAL_QUERY, SOURCE_HASH } from './model.mjs';
const raw = readFileSync(new URL('./catalogue.json', import.meta.url));
const original = readFileSync(new URL('../task/input.json', import.meta.url));
assert.deepEqual(raw, original);
assert.equal(createHash('sha256').update(raw).digest('hex'), SOURCE_HASH);
const catalogue = JSON.parse(raw);
const ids = query => filterRecords(catalogue.records, query).map(record => record.id);
assert.deepEqual(ids(INITIAL_QUERY), ['demo-image-01','demo-image-02','demo-image-03','demo-image-06']);
assert.deepEqual(ids({...INITIAL_QUERY,text:'construction'}),['demo-image-01','demo-image-03']);
assert.deepEqual(ids({text:'',attribution:'Northfield workshop',role:'publisher'}),['demo-image-04']);
assert.deepEqual(ids({text:'zzz-no-match',attribution:'',role:''}),[]);
assert.equal(ids({text:'',attribution:'',role:''}).length,12);
const state = { query:{...INITIAL_QUERY},selectedIds:['demo-image-03','demo-image-01','demo-image-02'],question:'  Open question\r\nwith retained spacing  ',observation:'\nObservation\n' };
const exported = makeInvestigation(catalogue,state);
assert.deepEqual(exported.records, state.selectedIds.map(id => catalogue.records.find(record => record.id === id)));
assert.deepEqual(readInvestigation(JSON.parse(JSON.stringify(exported)),catalogue),state);
const altered = structuredClone(exported); altered.records[0].places[0].coordinates = [0,0]; assert.throws(() => readInvestigation(altered,catalogue));
const extra = structuredClone(exported); extra.records[0].surprise = 'do not drop'; assert.throws(() => readInvestigation(extra,catalogue));
const duplicate = structuredClone(exported); duplicate.selectedIds[1] = duplicate.selectedIds[0]; assert.throws(() => readInvestigation(duplicate,catalogue));
const unknown = structuredClone(exported); unknown.surprise = 'reject'; assert.throws(() => readInvestigation(unknown,catalogue));
const tooLong = structuredClone(exported); tooLong.interpretation.unresolvedQuestion = 'q'.repeat(20001); assert.throws(() => readInvestigation(tooLong,catalogue));
const download = JSON.parse(readFileSync(new URL('./evidence/browser-download.json', import.meta.url),'utf8'));
assert.deepEqual(download.selectedIds,['demo-image-01','demo-image-02','demo-image-03']);
assert.deepEqual(download.records,catalogue.records.slice(0,3));
assert.deepEqual(download.source,catalogue.source);
assert.equal(download.interpretation.unresolvedQuestion,'Can records DEMO-A-01 to DEMO-A-03 be linked to one construction project, despite the missing depicted location and unreviewed place extraction?');
assert.equal(download.records[2].production['places[0]'].sourceText,'Possibly taken by the harbour in the north.');
assert.equal(download.records[2].production['places[0]'].review,null);
readInvestigation(download,catalogue);
writeFileSync(new URL('./evidence/rejected-source.json', import.meta.url),JSON.stringify(altered,null,2));
console.log('PASS: source bytes and SHA-256; scoped filters and zero results; all selected fields; exact authored whitespace; round trip; rejection of changed, extra, duplicate and oversized fields; actual browser download with source semantics and field production.');
